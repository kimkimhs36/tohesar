#!/usr/bin/env python3
"""TOHEŞAR 01: lossless source-locked 82mm chest vector -> transparent 300/600 DPI PNG.

Run from any directory after checking out branch object-lab/apparel-first-drop-r02-20261109.
Requires: pip install resvg_py pillow
No artwork is regenerated by AI or fonts. This is a raster export only.
"""
from __future__ import annotations
import hashlib
import io
import json
from pathlib import Path
from xml.etree import ElementTree as ET
from PIL import Image
import resvg_py

ROOT = Path(__file__).resolve().parents[3]
BASE = Path(__file__).resolve().parent
MASTER = ROOT / "assets" / "wordmark.svg"
ART = BASE / "01-SHADOW-CHEST-82MM-ORIGINAL-PATH-IVORY.svg"
EXPECTED_GIT_BLOB = "e9b299f8d797625b3704103c08ea1aede5c5ea05"
W_MM = 82.0

def git_blob_sha(raw: bytes) -> str:
    return hashlib.sha1(f"blob {len(raw)}\0".encode() + raw).hexdigest()

def path_nodes(path: Path):
    root = ET.parse(path).getroot()
    return root, [node for node in root.iter() if node.tag.endswith("}path") or node.tag == "path"]

def main():
    raw = MASTER.read_bytes()
    source_sha = git_blob_sha(raw)
    if source_sha != EXPECTED_GIT_BLOB:
        raise RuntimeError(f"Source art hash changed: {source_sha}; stop rather than replacing the logo")
    source_root, source_paths = path_nodes(MASTER)
    art_root, art_paths = path_nodes(ART)
    if len(source_paths) != 1 or len(art_paths) != 1:
        raise RuntimeError("Expected a single vector path in each SVG")
    if source_paths[0].attrib.get("d") != art_paths[0].attrib.get("d"):
        raise RuntimeError("Artwork path changed; export aborted")
    if art_root.attrib.get("width") != "82mm" or art_root.attrib.get("viewBox") != "0 0 1109 255":
        raise RuntimeError("Physical width or aspect reference changed; export aborted")
    if art_paths[0].attrib.get("fill") != "#f8f2e7":
        raise RuntimeError("Ivory fill changed; export aborted")
    if any(node.tag.endswith("}text") or node.tag == "text" for node in art_root.iter()):
        raise RuntimeError("Live text found; export aborted")
    outputs = []
    for dpi in (300, 600):
        target_px = round(W_MM / 25.4 * dpi)
        png_bytes = resvg_py.svg_to_bytes(svg_path=str(ART), width=target_px)
        with Image.open(io.BytesIO(png_bytes)) as im:
            rgba = im.convert("RGBA")
            lo, hi = rgba.getchannel("A").getextrema()
            if lo != 0 or hi != 255 or rgba.width != target_px:
                raise RuntimeError("PNG transparency or pixel dimensions failed QC")
            outfile = BASE / f"01-SHADOW-CHEST-82MM-IVORY-{dpi}DPI.png"
            rgba.save(outfile, format="PNG", dpi=(dpi, dpi), optimize=True)
            outputs.append({
                "file": outfile.name, "dpi": dpi,
                "pixels": [rgba.width, rgba.height],
                "sha256": hashlib.sha256(outfile.read_bytes()).hexdigest(),
                "alpha_extrema": [lo, hi]
            })
    report = {"source_git_blob_sha": source_sha, "physical_width_mm": W_MM,
              "source_path_identity": True, "approved_for_vendor": False, "exports": outputs}
    report_file = BASE / "01-SHADOW-CHEST-82MM-EXPORT-MANIFEST.json"
    report_file.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))

if __name__ == "__main__":
    main()
